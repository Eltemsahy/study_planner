"""SYNTHETIC OULAD-shaped tables, ONLY for testing the pipeline offline.

It is NOT real data. Everything produced here is flagged synthetic in
DATA_DICTIONARY.md and make_data.py writes a SYNTHETIC marker file.
"""
import numpy as np
import pandas as pd
from .. import config as C

TMA_DAYS = [19, 54, 110, 152, 187, 222]        # deadlines (days) of 6 TMAs
WEIGHTS = [10, 15, 15, 20, 20, 20]
SITES = [("resource", 1), ("oucontent", 2), ("forumng", 3), ("quiz", 4), ("homepage", 5), ("url", 6)]


def generate(raw_dir=C.RAW_DIR, seed=C.SEED, n_students=350):
    rng = np.random.default_rng(seed)
    pres = C.TRAIN_PRESENTATIONS + C.TEST_PRESENTATIONS
    ass_rows, sa_rows, vle_rows, svle = [], [], [], []
    aid = 1000
    for p in pres:
        for site, sid in SITES:
            vle_rows.append((sid + 100 * pres.index(p), C.MODULE, p, site))
        ids = []
        for day, wt in zip(TMA_DAYS, WEIGHTS):
            aid += 1
            ids.append(aid)
            ass_rows.append((C.MODULE, p, aid, "TMA", day, wt))
        aid += 1
        ass_rows.append((C.MODULE, p, aid, "Exam", np.nan, 100))
        ability = rng.normal(0, 1, n_students)
        engage = rng.lognormal(0, 0.5, n_students)
        for s in range(n_students):
            sid_ = pres.index(p) * 10_000 + s
            weekly = np.zeros(36)
            for w in range(36):
                dropout = 1.0 if w < 8 + 28 * rng.random() else 0.2
                weekly[w] = rng.poisson(100 * engage[s] * (1 + 0.2 * ability[s]) * dropout)
            for w in range(36):
                if weekly[w] <= 0:
                    continue
                split = rng.multinomial(int(weekly[w]), [0.55, 0.15, 0.30])
                for gi, (site_idx) in enumerate([0, 2, 3]):
                    if split[gi]:
                        svle.append((C.MODULE, p, sid_, SITES[site_idx][1] + 100 * pres.index(p),
                                     w * 7 + int(rng.integers(0, 7)), int(split[gi])))
            prev = []
            for day, a in zip(TMA_DAYS, ids):
                dw = day // 7
                c4 = weekly[max(0, dw - 4):dw].sum()
                base = 52 + 9 * ability[s] + 10 * np.log1p(c4 / 150)
                if prev:
                    base = 0.6 * base + 0.4 * np.mean(prev)
                score = float(np.clip(base + rng.normal(0, 7), 0, 100))
                if c4 > 0 and rng.random() > 0.08:       # 8% do not submit
                    prev.append(score)
                    sa_rows.append((a, sid_, day - 1, 0, round(score)))
    raw_dir.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(ass_rows, columns=["code_module", "code_presentation", "id_assessment",
                 "assessment_type", "date", "weight"]).to_csv(raw_dir / "assessments.csv", index=False)
    pd.DataFrame(sa_rows, columns=["id_assessment", "id_student", "date_submitted",
                 "is_banked", "score"]).to_csv(raw_dir / "studentAssessment.csv", index=False)
    pd.DataFrame(vle_rows, columns=["id_site", "code_module", "code_presentation",
                 "activity_type"]).to_csv(raw_dir / "vle.csv", index=False)
    pd.DataFrame(svle, columns=["code_module", "code_presentation", "id_student",
                 "id_site", "date", "sum_click"]).to_csv(raw_dir / "studentVle.csv", index=False)
    (raw_dir / "SYNTHETIC_DATA.txt").write_text(
        "These CSVs were generated by planner.data.synthetic (NOT real OULAD).\n")
